export const messages: Record<Locale, Record<MessageKey, string>> = { en, kn, hi }

export function detectDeviceLocale(): Locale {
  const langs = [
    ...(typeof navigator !== 'undefined' ? navigator.languages || [] : []),
    typeof navigator !== 'undefined' ? navigator.language : 'en',
  ]
  for (const raw of langs) {
    const code = (raw || '').toLowerCase()
    if (code.startsWith('kn')) return 'kn'
    if (code.startsWith('hi')) return 'hi'
  }
  return 'en'
}

export function formatMessage(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template
  // {n?singular|plural} picks a word based on the count, so "1 dates" can never render.
  const n = Number(vars.n)
  return template
    .replace(/\{n\?([^|{}]*)\|([^|{}]*)\}/g, (_, one: string, many: string) =>
      n === 1 ? one : many,
    )
    .replace(/\{(\w+)\}/g, (_, key: string) =>
      vars[key] != null ? String(vars[key]) : `{${key}}`,
    )
}
